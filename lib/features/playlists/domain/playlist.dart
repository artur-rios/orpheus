import '../../library/domain/music_entry.dart';

/// A playlist's name as it will be stored: trimmed, or `null` when it is blank.
///
/// The one rule for what counts as a name, shared by creating and renaming so
/// the two cannot disagree.
String? validPlaylistName(String text) => trimmedOrNull(text);

/// [playlists] in the order every list of them shows: the most recently
/// changed first.
///
/// Two changed in the same instant go the more recently made first, and then
/// by id, so the order never depends on how they happened to be stored. A new
/// list: [playlists] is left as it was.
List<Playlist> mostRecentFirst(Iterable<Playlist> playlists) =>
    [...playlists]..sort((a, b) {
      final changed = b.modifiedAt.compareTo(a.modifiedAt);
      if (changed != 0) return changed;
      final made = b.createdAt.compareTo(a.createdAt);
      if (made != 0) return made;
      return a.id.compareTo(b.id);
    });

/// One place in a playlist: a song's file, and what it was called when added.
///
/// It has an id of its own because the same song may be in a playlist twice,
/// and each copy must be movable and removable on its own. The title, artist,
/// album and duration are a snapshot: while the song is in the library the
/// catalog's current tags are what is shown, and the snapshot is what a row
/// and an exported file fall back to when the song is missing.
class PlaylistEntry {
  /// Creates an entry.
  const PlaylistEntry({
    required this.id,
    required this.path,
    this.title,
    this.artist,
    this.album,
    this.duration,
  });

  /// What identifies this place in this playlist, generated by the caller.
  final String id;

  /// The song's file.
  final String path;

  /// The song's title when it was added or last refreshed.
  final String? title;

  /// The song's artist when it was added or last refreshed.
  final String? artist;

  /// The song's album when it was added or last refreshed.
  final String? album;

  /// The song's length when it was added or last refreshed.
  final Duration? duration;

  /// This entry with its snapshot taken again from [song].
  ///
  /// Keeps the id and the path: it is the same place in the playlist, told
  /// what the catalog now says about the song in it.
  PlaylistEntry refreshedFrom(MusicEntry song) => PlaylistEntry(
    id: id,
    path: path,
    title: song.title,
    artist: song.artist,
    album: song.album,
    duration: song.duration,
  );

  @override
  bool operator ==(Object other) =>
      other is PlaylistEntry &&
      other.id == id &&
      other.path == path &&
      other.title == title &&
      other.artist == artist &&
      other.album == album &&
      other.duration == duration;

  @override
  int get hashCode => Object.hash(id, path, title, artist, album, duration);
}

/// A named, ordered list of songs the owner made.
///
/// Immutable: every change is a new playlist, stamped with the time it was
/// made at. The clock is an argument rather than a call so the domain stays
/// deterministic, and ids are made by the caller for the same reason.
class Playlist {
  /// Creates a playlist.
  const Playlist({
    required this.id,
    required this.name,
    this.entries = const [],
    this.coverId,
    required this.createdAt,
    required this.modifiedAt,
  });

  /// What identifies this playlist, generated by the caller and stable for
  /// its life — names are labels, and two playlists may share one.
  final String id;

  /// What it is called, trimmed and not blank.
  final String name;

  /// Its songs, in the order they play.
  final List<PlaylistEntry> entries;

  /// The custom cover the owner chose, or `null` for the mosaic.
  final String? coverId;

  /// When it was made.
  final DateTime createdAt;

  /// When it last changed, which is what the lists are ordered by.
  final DateTime modifiedAt;

  /// This playlist under [name].
  ///
  /// Throws an [ArgumentError] when [name] is blank: a caller that let the
  /// owner submit nothing has a bug to fix, and a playlist with no name would
  /// be a row with nothing to read.
  Playlist renamed(String name, DateTime at) {
    final valid = validPlaylistName(name);
    if (valid == null) {
      throw ArgumentError.value(name, 'name', 'must not be blank');
    }
    return _copy(name: valid, at: at);
  }

  /// This playlist with [added] at the end, in the order given.
  Playlist adding(List<PlaylistEntry> added, DateTime at) =>
      _copy(entries: [...entries, ...added], at: at);

  /// This playlist without the entries whose ids are in [entryIds].
  ///
  /// By entry id rather than path: removing one copy of a song that is in the
  /// list twice leaves the other.
  Playlist removing(Set<String> entryIds, DateTime at) => _copy(
    entries: [
      for (final entry in entries)
        if (!entryIds.contains(entry.id)) entry,
    ],
    at: at,
  );

  /// This playlist with the entry at [from] moved to [to].
  ///
  /// [to] follows `ReorderableListView`'s rule: it is the index the entry was
  /// dropped at *before* it is taken out of the list, so moving forward lands
  /// one place earlier than [to] says. Both run from `0` to the length;
  /// anything else throws a [RangeError].
  Playlist moving(int from, int to, DateTime at) {
    RangeError.checkValidIndex(from, entries, 'from');
    RangeError.checkValueInInterval(to, 0, entries.length, 'to');
    final moved = [...entries];
    final entry = moved.removeAt(from);
    moved.insert(from < to ? to - 1 : to, entry);
    return _copy(entries: moved, at: at);
  }

  /// This playlist with [coverId] as its custom cover, or with none.
  Playlist withCover(String? coverId, DateTime at) => Playlist(
    id: id,
    name: name,
    entries: entries,
    coverId: coverId,
    createdAt: createdAt,
    modifiedAt: at,
  );

  /// The files in this playlist, each once however often it is in it.
  ///
  /// What the duplicate question compares the songs about to be added with.
  Set<String> pathsIn() => {for (final entry in entries) entry.path};

  Playlist _copy({String? name, List<PlaylistEntry>? entries, DateTime? at}) =>
      Playlist(
        id: id,
        name: name ?? this.name,
        entries: entries ?? this.entries,
        coverId: coverId,
        createdAt: createdAt,
        modifiedAt: at ?? modifiedAt,
      );

  @override
  bool operator ==(Object other) =>
      other is Playlist &&
      other.id == id &&
      other.name == name &&
      other.coverId == coverId &&
      other.createdAt == createdAt &&
      other.modifiedAt == modifiedAt &&
      _sameEntries(other.entries, entries);

  @override
  int get hashCode => Object.hash(
    id,
    name,
    coverId,
    createdAt,
    modifiedAt,
    Object.hashAll(entries),
  );
}

bool _sameEntries(List<PlaylistEntry> a, List<PlaylistEntry> b) {
  if (a.length != b.length) return false;
  for (var i = 0; i < a.length; i++) {
    if (a[i] != b[i]) return false;
  }
  return true;
}
